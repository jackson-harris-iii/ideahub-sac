import assert from 'node:assert/strict';
const base=process.env.TEST_BASE||'http://127.0.0.1:18766';
if(!['localhost','127.0.0.1'].includes(new URL(base).hostname))throw Error('Local preview only.');
const login=await fetch(base+'/signin-with-chatgpt?return_to=/admin',{redirect:'manual'});
const cookie=login.headers.getSetCookie().map(c=>c.split(';')[0]).join('; ');
const pub=async()=>await(await fetch(base+'/api/community')).json();
const adm=async()=>await(await fetch(base+'/api/admin',{headers:{Cookie:cookie}})).json();
const post=(body,auth=true,origin=base)=>fetch(base+'/api/admin',{method:'POST',headers:{'Content-Type':'application/json',Origin:origin,...(auth?{Cookie:cookie}:{})},body:JSON.stringify(body)});
const initial=await pub();
assert.equal(initial.ideas.find(i=>i.id==='glass-onion').projectStatus,'ready');
assert.ok(initial.ideas.find(i=>i.id==='glass-onion').demoUrl.startsWith('https://'));
const original=initial.ideas.find(i=>i.projectStatus==='idea');
const change={type:'project-progress',id:original.id,status:'building',demoUrl:''};
assert.equal((await post(change,false)).status,403);
assert.equal((await post(change,true,'https://bad.example')).status,403);
for(const patch of [{status:'launched'},{status:'ready'},{demoUrl:'javascript:alert(1)'},{demoUrl:'http://example.test'},{demoUrl:'https://user:pass@example.test'}])assert.equal((await post({...change,...patch})).status,400);
assert.equal((await post({...change,id:'unknown'})).status,404);
assert.equal((await post(change)).status,200);
assert.equal((await pub()).ideas.find(i=>i.id===original.id).projectStatus,'building');
assert.equal((await adm()).rankings.find(i=>i.id===original.id).projectStatus,'building');
assert.equal((await post({...change,status:'ready',demoUrl:'https://example.test/demo'})).status,200);
assert.equal((await pub()).ideas.find(i=>i.id===original.id).demoUrl,'https://example.test/demo');
assert.deepEqual((await pub()).counts,initial.counts,'Status changes do not change votes');
assert.equal((await post({...change,status:original.projectStatus,demoUrl:original.demoUrl})).status,200);
const id=crypto.randomUUID();
assert.equal((await fetch(base+'/api/community',{method:'POST',headers:{Origin:base,'Content-Type':'application/json'},body:JSON.stringify({action:'submit',id,title:'Local progress QA',audience:'Local QA',problem:'Synthetic test of project progress and moderation.',approach:'Local only test.'})})).status,201);
const custom={...change,id:'submission-'+id};
assert.equal((await post(custom)).status,404,'Pending submissions cannot receive public progress');
assert.equal((await post({id,status:'approved'})).status,200);
assert.equal((await post(custom)).status,200);
assert.equal((await pub()).ideas.find(i=>i.id===custom.id).projectStatus,'building');
assert.equal((await post({id,status:'rejected'})).status,200);
assert.ok(!(await pub()).ideas.some(i=>i.id===custom.id));
assert.equal((await post({action:'test-notification'},false)).status,403);
assert.equal((await post({action:'test-notification'})).status,409,'Local preview has no real email credentials');
console.log('PASS: public defaults, private editing, origin protection, status/link validation, persistence, independent votes, moderation visibility, test-email protections.');
